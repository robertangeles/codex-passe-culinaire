import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'

test('kitchen film loads on demand, preserves pause, seeks and plays to its finite end', async ({ page }, testInfo) => {
  test.setTimeout(190000)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  const mediaRequests: string[] = []
  const errors: string[] = []
  page.on('request', request => { if (request.url().endsWith('.mp4')) mediaRequests.push(request.url()) })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/', { waitUntil: 'networkidle' })
  const film = page.locator('#kitchen-story')
  const video = film.locator('video')
  expect(mediaRequests).toEqual([])
  await expect(video).not.toHaveAttribute('src', /./)
  await video.scrollIntoViewIfNeeded()
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => !v.paused)).toBe(true)
  const portrait = (page.viewportSize()?.width ?? 0) <= 760
  await expect(video).toHaveAttribute('src', new RegExp(portrait ? 'portrait-v1.mp4' : 'landscape-v1.mp4'))
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.duration)).toBe(128)
  await film.getByRole('button', { name: 'Pause the kitchen film', exact: true }).click()
  await page.evaluate(() => window.scrollTo(0, 0))
  await video.scrollIntoViewIfNeeded()
  await page.waitForTimeout(300)
  expect(await video.evaluate((v: HTMLVideoElement) => v.paused)).toBe(true)
  await film.getByRole('button', { name: /Recipe Lab/ }).click()
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.currentTime)).toBe(23)
  await expect(film.locator('h4[data-film-title]')).toHaveText('An idea becomes a recipe.')
  await expect(film.getByRole('button', { name: /Recipe Lab/ })).toHaveAttribute('aria-current', 'step')
  await video.scrollIntoViewIfNeeded()
  const axe = await new AxeBuilder({ page }).include('#kitchen-story').withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
  expect(axe.violations).toEqual([])
  await film.getByRole('button', { name: 'Play the kitchen film', exact: true }).click()
  await page.evaluate(() => window.scrollTo(0, 0))
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.paused)).toBe(true)
  await video.scrollIntoViewIfNeeded()
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => !v.paused)).toBe(true)
  await film.getByRole('button', { name: 'Pause the kitchen film', exact: true }).click()
  await video.evaluate((v: HTMLVideoElement) => { v.currentTime = 0 })
  await video.scrollIntoViewIfNeeded()
  await film.getByRole('button', { name: 'Play the kitchen film', exact: true }).click()
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.ended), { timeout: 145000, intervals: [1000] }).toBe(true)
  await expect(film.getByRole('button', { name: 'Replay the kitchen film', exact: true })).toBeVisible()
  expect(await video.evaluate((v: HTMLVideoElement) => v.currentTime)).toBe(128)
  await testInfo.attach('kitchen-film-playback.json', { body: JSON.stringify(await video.evaluate((v: HTMLVideoElement) => ({ time: v.currentTime, duration: v.duration, source: v.currentSrc, totalFrames: v.getVideoPlaybackQuality().totalVideoFrames, droppedFrames: v.getVideoPlaybackQuality().droppedVideoFrames }))), contentType: 'application/json' })
  await film.getByRole('button', { name: 'Replay the kitchen film', exact: true }).click()
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.currentTime)).toBeLessThan(5)
  expect(errors).toEqual([])
  expect(mediaRequests.every(url => url.includes(portrait ? 'portrait-v1' : 'landscape-v1'))).toBe(true)
})

test('reduced motion starts paused and failed media leaves the written story available', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  const film = page.locator('#kitchen-story')
  const video = film.locator('video')
  await video.scrollIntoViewIfNeeded()
  await expect(film.getByRole('button', { name: 'Play the kitchen film', exact: true })).toBeVisible()
  expect(await video.evaluate((v: HTMLVideoElement) => v.paused)).toBe(true)
  await film.getByRole('button', { name: 'Play the kitchen film', exact: true }).click()
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => !v.paused)).toBe(true)
  await page.route('**/films/kitchen-day/*.mp4', route => route.abort())
  await page.reload()
  await video.scrollIntoViewIfNeeded()
  await film.getByRole('button', { name: 'Play the kitchen film', exact: true }).click()
  await expect(film.locator('[data-film-error]')).toBeVisible()
  await expect(film.locator('[data-film-poster]')).toBeVisible()
  await film.getByText('Read the full kitchen story', { exact: true }).click()
  await expect(film.locator('details li')).toHaveCount(15)
})

test('the film story and poster remain available without JavaScript', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ javaScriptEnabled: false, baseURL })
  const page = await context.newPage()
  await page.goto('/')
  const film = page.locator('#kitchen-story')
  await film.scrollIntoViewIfNeeded()
  await expect(film.locator('[data-film-poster]')).toBeVisible()
  await film.getByText('Read the full kitchen story', { exact: true }).click()
  await expect(film.locator('details li')).toHaveCount(15)
  await expect(film.getByRole('link', { name: 'Open the landscape film' })).toBeVisible()
  await context.close()
})
